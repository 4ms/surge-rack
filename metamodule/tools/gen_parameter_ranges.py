"""Generate dsp/compat/ParameterRanges.h from surge's Parameter::set_type.

The embedded Parameter stand-in only needs the value type, range and default of
the control types that the compiled Surge sources reference. Rerun after
updating the surge submodule:

    python3 metamodule/tools/gen_parameter_ranges.py
"""
import pathlib
import re
import sys

here = pathlib.Path(__file__).resolve().parent
mm = here.parent
common = mm.parent / "surge" / "src" / "common"
out = mm / "dsp" / "compat" / "ParameterRanges.h"

# Surge sources compiled against the stand-in (see CMakeLists.txt); their ct_ names
# plus the ones the port's engines set directly.
scanned = [
    *sorted((common / "dsp" / "oscillators").glob("*.cpp")),
    *[common / "dsp" / "effects" / f for f in (
        "ChorusEffect.h", "ChorusEffectImpl.h", "Reverb2Effect.cpp", "BBDEnsembleEffect.cpp",
        "NimbusEffect.cpp", "CombulatorEffect.cpp", "ResonatorEffect.cpp", "VocoderEffect.cpp",
        "DistortionEffect.cpp", "FrequencyShifterEffect.cpp", "RingModulatorEffect.cpp",
        "RotarySpeakerEffect.cpp", "TreemonsterEffect.cpp", "chowdsp/NeuronEffect.cpp",
        "chowdsp/ExciterEffect.cpp", "chowdsp/CHOWEffect.cpp", "chowdsp/SpringReverbEffect.cpp")],
    common / "dsp" / "Effect.cpp",
    mm / "dsp" / "compat" / "SurgeStorage.h",
    *sorted((mm / "dsp").glob("*.cpp")),
    *sorted((mm / "dsp").glob("*.h")),
]
used = set()
for f in scanned:
    used |= set(re.findall(r"\bct_[a-z0-9_]+\b", f.read_text(errors="replace")))
used.add("ct_none")

src = (common / "Parameter.cpp").read_text()
body = src[src.index("void Parameter::set_type(int ctrltype)"):src.index("void Parameter::bound_value")]
switches = [m.start() for m in re.finditer(r"switch \(ctrltype\)", body)]


def cases(text):
    """Map each case label to the statements up to its break."""
    result, labels, stmts = {}, [], []
    for line in text.splitlines():
        line = line.split("//")[0].strip()
        m = re.match(r"case (ct_\w+):$", line)
        if m:
            if stmts:
                labels, stmts = [], []
            labels.append(m.group(1))
            continue
        if line == "default:":
            labels, stmts = [], []
            continue
        if not labels or not line:
            continue
        if line == "break;":
            for label in labels:
                result[label] = stmts
            labels, stmts = [], []
        else:
            stmts.append(line)
    return result


ranges = cases(body[switches[0]:switches[1]])
display = cases(body[switches[1]:switches[2]])

# Fold "x_count()" helpers that return a constant, so the ranges do not depend on
# which effect sources are linked; declare any that remain.
counts = {}
for f in common.rglob("*.cpp"):
    for name, value in re.findall(r"int (\w+_count)\(\)\s*\{\s*return (\d+);\s*\}", f.read_text(errors="replace")):
        counts[name] = value
externs = set()


def fold(stmt):
    def sub(m):
        if m.group(1) in counts:
            return counts[m.group(1)]
        externs.add(m.group(1))
        return m.group(0)
    return re.sub(r"\b(\w+_count)\(\)", sub, stmt)


lines = []
for ct in sorted(used):
    keep = [s for s in ranges.get(ct, []) if re.match(r"(valtype|val_(min|max|default)\.[fib]) =", s)]
    keep += [s for s in display.get(ct, []) if s.startswith("displayInfo.b =")]
    if not keep:
        continue
    if any(re.search(r"\b(if|else|for)\b|\?", s) for s in keep):
        sys.exit(f"{ct}: conditional range, update the generator")
    lines.append(f"    case {ct}:")
    lines += [f"        p.{fold(s)}" for s in keep]
    lines.append("        break;")

enum = ",\n    ".join(sorted(used))
decls = "".join(f"int {name}();\n" for name in sorted(externs))
out.write_text(f"""// SPDX-License-Identifier: GPL-3.0-or-later
// Generated by metamodule/tools/gen_parameter_ranges.py from surge's
// Parameter::set_type. Do not edit; rerun the script after updating surge.
#pragma once
#include <cmath>

{decls}
// Only the control types referenced by the Surge sources this port compiles. The
// numbering is local to the port and never stored.
enum ctrltypes
{{
    {enum},
    num_ctrltypes
}};

template <typename P> void set_parameter_range(P &p, int ctrltype)
{{
    switch (ctrltype)
    {{
{chr(10).join(lines)}
    default:
        break;
    }}
}}
""")
print(f"{out}: {len(used)} control types")
